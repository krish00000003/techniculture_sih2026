/**
 * Role-based access control middleware.
 * Usage: roleGuard('admin', 'provider')
 */
module.exports = (...allowedRoles) => {
  return (req, res, next) => {
    if (!req.user || !allowedRoles.includes(req.user.role)) {
      return res.status(403).json({ message: 'Access denied' });
    }
    next();
  };
};
